export function dailyInspiration(localDate: string, gender?: Gender): string {
  // UTC is used only for date arithmetic, not to select the user's local day.
  const stamp = Date.parse(`${localDate}T00:00:00Z`);
  if (!Number.isFinite(stamp)) return 'У вас всё получится!';
  const day = Math.floor(stamp / 86_400_000);
  const phrase = PHRASES[((day % PHRASES.length) + PHRASES.length) % PHRASES.length];
  if (typeof phrase === 'string') return phrase;
  return gender === 'female' ? phrase.female : gender === 'male' ? phrase.male : phrase.neutral;
}
